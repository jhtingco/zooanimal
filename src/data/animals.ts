// 특정 동물원의 전체 동물 목록을 가져오는 함수 (없을 경우 keyAnimals 기반 기본 목록 생성)
export function getAnimalsForZoo(
  zooId: string,
  keyAnimals: string[] = []
): AnimalItem[] {
  if (ZOO_ANIMALS_MAP[zooId]) {
    return ZOO_ANIMALS_MAP[zooId];
  }

  // 데이터가 아직 전수 조사되지 않은 동물원의 경우, 기본 keyAnimals를 정형화하여 반환
  return keyAnimals.map((name, index) => {
    const isBird = /학|두루미|새|앵무|독수리|펭귄|부엉이|오리/.test(name);
    const isReptile = /뱀|거북|악어|도마뱀|이구아나/.test(name);
    const isMarine = /상어|고래|물범|물개|가오리|해마|어류|물고기/.test(name);

    return {
      id: `${zooId}-gen-${index}`,
      name,
      className: isMarine
        ? "어류/해양"
        : isBird
        ? "조류"
        : isReptile
        ? "파충류"
        : "포유류",
      zone: "일반 전시 구역",
      highlights: `${name}의 대표 생태 환경과 관람 특성이 전시되어 있습니다.`,
      isKeyAnimal: true,
    };
  });
}
